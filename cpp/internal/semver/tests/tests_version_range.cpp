void assertAllVersionRangesHaveIdenticalStrings(
    T* t, const std::string& name, const std::vector<std::string>& strs) {
	t->Run(name, [&strs](T* t) {
		t->Parallel();
		for (auto& s1 : strs) {
			for (auto& s2 : strs) {
				t->Run(s1 + " == " + s2, [s1, s2](T* t) {
					auto [v1, ok1] = TryParseVersionRange(s1);
					assert::Assert(t, ok1);
					auto [v2, ok2] = TryParseVersionRange(s2);
					assert::Assert(t, ok2);
					assert::Equal(t, v1.String(), v2.String());
				});
			}
		}
	});
}

void TestWildcardsHaveSameString(T* t) {
	t->Parallel();
	std::vector<std::string> majorWildcardStrings = {"", "*", "*.*", "*.*.*", "x", "x.x", "x.x.x", "X", "X.X", "X.X.X"};
	std::vector<std::string> minorWildcardStrings = {"1", "1.*", "1.*.*", "1.x", "1.x.x", "1.X", "1.X.X"};
	std::vector<std::string> patchWildcardStrings = {"1.2", "1.2.*", "1.2.x", "1.2.X"};
	std::vector<std::string> mixedCaseWildcardStrings = {"x", "X", "*", "x.X.x", "X.x.*"};

	assertAllVersionRangesHaveIdenticalStrings(t, "majorWildcardStrings", majorWildcardStrings);
	assertAllVersionRangesHaveIdenticalStrings(t, "minorWildcardStrings", minorWildcardStrings);
	assertAllVersionRangesHaveIdenticalStrings(t, "patchWildcardStrings", patchWildcardStrings);
	assertAllVersionRangesHaveIdenticalStrings(t, "mixedCaseWildcardStrings", mixedCaseWildcardStrings);
}

void assertRangesGoodBad(T* t, const std::string& versionRangeString,
                         const std::vector<std::string>& good,
                         const std::vector<std::string>& bad) {
	t->Run(versionRangeString, [versionRangeString, good, bad](T* t) {
		t->Parallel();
		auto [versionRange, ok] =
		    TryParseVersionRange(versionRangeString);
		assert::Assert(t, ok);
		for (auto& g : good) {
			auto [v, ok2] = TryParseVersion(g);
			assert::Assert(t, ok2);
			assert::Assert(t, versionRange.Test(&v),
			               g + " should be matched by range " +
			                   versionRangeString);
		}

		for (auto& b : bad) {
			auto [v, ok2] = TryParseVersion(b);
			assert::Assert(t, ok2);
			assert::Assert(t, !versionRange.Test(&v),
			               b + " should not be matched by range " +
			                   versionRangeString);
		}
	});
}

void TestVersionRanges(T* t) {
	t->Parallel();
	// strings.Repeat("1", 320)
	const std::string lottsaOnes(320, '1');
    assertRangesGoodBad(t, "1", {"1.0.0", "1.9.9", "1.0.0-pre", "1.0.0+build"}, {"0.0.0", "2.0.0", "0.0.0-pre", "0.0.0+build"});
    assertRangesGoodBad(t, "1.2", {"1.2.0", "1.2.9", "1.2.0-pre", "1.2.0+build"}, {"1.1.0", "1.3.0", "1.1.0-pre", "1.1.0+build"});
    assertRangesGoodBad(t, "1.2.3", {"1.2.3", "1.2.3+build"}, {"1.2.2", "1.2.4", "1.2.2-pre", "1.2.2+build", "1.2.3-pre"});
    assertRangesGoodBad(t, "1.2.3-pre", {"1.2.3-pre", "1.2.3-pre+build.stuff"}, {"1.2.3", "1.2.3-pre.0", "1.2.3-pre.9", "1.2.3-pre.0+build", "1.2.3-pre.9+build", "1.2.3+build", "1.2.4"});
    assertRangesGoodBad(t, "<3.8.0", {"3.6", "3.7"}, {"3.8", "3.9", "4.0"});
    assertRangesGoodBad(t, "<=3.8.0", {"3.6", "3.7", "3.8"}, {"3.9", "4.0"});
    assertRangesGoodBad(t, ">3.8.0", {"3.9", "4.0"}, {"3.6", "3.7", "3.8"});
    assertRangesGoodBad(t, ">=3.8.0", {"3.8", "3.9", "4.0"}, {"3.6", "3.7"});
    assertRangesGoodBad(t, "<3.8.0-0", {"3.6", "3.7"}, {"3.8", "3.9", "4.0"});
    assertRangesGoodBad(t, "<=3.8.0-0", {"3.6", "3.7"}, {"3.8", "3.9", "4.0"});
    assertRangesGoodBad(t, ">=1.2.3-1" + lottsaOnes, {std::string("1.2.3-1") + lottsaOnes, std::string("1.2.3-11") + lottsaOnes + ".1", std::string("1.2.3-1") + lottsaOnes + ".1+build"}, {std::string("1.2.3-") + lottsaOnes + ".1+build"});
}

void assertRangeTest(T* t, const std::string& name,
                     const std::string& rangeText,
                     const std::string& versionText, bool inRange) {
	std::string testName = name + " (version " + versionText +
	                       " in range " + rangeText + ") == " +
	                       (inRange ? "true" : "false");
	t->Run(testName, [rangeText, versionText, inRange](T* t) {
		t->Parallel();
		auto [versionRange, ok] = TryParseVersionRange(rangeText);
		assert::Assert(t, ok);
		auto [version, ok2] = TryParseVersion(versionText);
		assert::Assert(t, ok2);
		assert::Equal(t, versionRange.Test(&version), inRange);
	});
}

