def gen_unicode():
    src = open(os.path.join(TSC, "stringutil", "identifier_parts_generated.go")).read()
    # unicodeESNextIdentifierStart = &unicode.RangeTable{ R16: []unicode.Range16{...}, R32: ..., LatinOffset: n}
    def parse_rt(varname):
        m = re.search(varname + r"\s*=\s*&unicode\.RangeTable\{(.*?)\}\n", src, re.S)
        body = m.group(1)
        def section(nm):
            m2 = re.search(nm + r":\s*\[\]unicode\.Range\d+\{(.*?)\n\s*\},", body, re.S)
            return [tuple(int(x, 0) for x in t.split(",")) for t in
                    re.findall(r"\{([^}]+)\}", m2.group(1))] if m2 else []
        lat = re.search(r"LatinOffset:\s*(\d+)", body)
        return section("R16"), section("R32"), int(lat.group(1)) if lat else 0

    lines = [HEADER, "#pragma once\n", "#include <cstdint>\n\nnamespace tsc {\n\n"]
    for var, cxx in [("unicodeESNextIdentifierStart", "kIdentifierStart"),
                     ("unicodeESNextIdentifierPart", "kIdentifierPart")]:
        r16, r32, lat = parse_rt(var)
        lines.append(f"inline constexpr uint16_t {cxx}R16[][3] = {{\n")
        for lo, hi, stride in r16:
            lines.append(f"\t{{{lo}, {hi}, {stride}}},\n")
        lines.append("};\n")
        lines.append(f"inline constexpr uint32_t {cxx}R32[][3] = {{\n")
        for lo, hi, stride in r32:
            lines.append(f"\t{{{lo}, {hi}, {stride}}},\n")
        lines.append("};\n")
        lines.append(f"inline constexpr int {cxx}LatinOffset = {lat};\n\n")
        print(f"{var}: {len(r16)} r16, {len(r32)} r32, latinOffset={lat}")
    lines.append("}  // namespace tsc\n")
    out = os.path.join(OUT, "stringutil", "unicode_tables.h")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w").write("".join(lines))
    print(f"wrote {out}")


